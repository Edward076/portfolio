def _掩码横截面排名(
    数据: pd.DataFrame,
    横截面掩码: pd.DataFrame,
) -> pd.DataFrame:
    """只在当日有效股票池内计算横截面百分位排名。"""
    数据, 横截面掩码 = 数据.align(横截面掩码, join="outer")
    return 横截面排名(数据.where(横截面掩码.fillna(False)))


def _条件动量因子(
    收盘价: pd.DataFrame,
    窗口: int,
) -> pd.DataFrame:
    """实现 Alpha9/10 共用的条件动量逻辑。"""
    一日价差 = 差分(收盘价, 1)
    窗口最小值 = 时间序列最小值(一日价差, 窗口)
    窗口最大值 = 时间序列最大值(一日价差, 窗口)
    窗口有效 = 窗口最小值.notna() & 窗口最大值.notna()

    因子 = -一日价差
    保持原方向 = 窗口最小值.gt(0) | 窗口最大值.lt(0)
    因子 = 因子.where(~保持原方向, 一日价差)
    return 因子.where(窗口有效)


def 计算第一批因子(
    开盘价: pd.DataFrame,
    收盘价: pd.DataFrame,
    最高价: pd.DataFrame,
    最低价: pd.DataFrame,
    成交量: pd.DataFrame,
    横截面掩码: pd.DataFrame,
) -> dict[str, pd.DataFrame]:
    """计算12个仅依赖OHLCV的第一批Alpha101因子。"""
    日收益 = 日收益率(收盘价)
    正成交量对数 = np.log(成交量.where(成交量.gt(0)))

    成交量对数变化排名 = _掩码横截面排名(
        差分(正成交量对数, 2),
        横截面掩码,
    )
    日内收益排名 = _掩码横截面排名(
        (收盘价 - 开盘价) / 开盘价.replace(0, np.nan),
        横截面掩码,
    )
    因子2 = -相关系数(成交量对数变化排名, 日内收益排名, 6)

    开盘价排名 = _掩码横截面排名(开盘价, 横截面掩码)
    成交量排名 = _掩码横截面排名(成交量, 横截面掩码)
    因子3 = -相关系数(开盘价排名, 成交量排名, 10)

    最低价排名 = _掩码横截面排名(最低价, 横截面掩码)
    因子4 = -时间序列排名(最低价排名, 9)

    因子6 = -相关系数(开盘价, 成交量, 10)

    五日开盘价和 = 时间序列求和(开盘价, 5)
    五日收益和 = 时间序列求和(日收益, 5)
    开盘收益乘积 = 五日开盘价和 * 五日收益和
    因子8 = -_掩码横截面排名(
        开盘收益乘积 - 延迟(开盘收益乘积, 10),
        横截面掩码,
    )

    因子9 = _条件动量因子(收盘价, 5)
    因子10 = _掩码横截面排名(
        _条件动量因子(收盘价, 4),
        横截面掩码,
    )

    因子12 = 符号(差分(成交量, 1)) * (-差分(收盘价, 1))

    收盘价排名 = _掩码横截面排名(收盘价, 横截面掩码)
    因子13 = -_掩码横截面排名(
        协方差(收盘价排名, 成交量排名, 5),
        横截面掩码,
    )

    因子14 = (
        -_掩码横截面排名(差分(日收益, 3), 横截面掩码)
        * 相关系数(开盘价, 成交量, 10)
    )

    最高价排名 = _掩码横截面排名(最高价, 横截面掩码)
    价量相关排名 = _掩码横截面排名(
        相关系数(最高价排名, 成交量排名, 3),
        横截面掩码,
    )
    因子15 = -时间序列求和(价量相关排名, 3)

    因子16 = -_掩码横截面排名(
        协方差(最高价排名, 成交量排名, 5),
        横截面掩码,
    )

    return {
        "Alpha2": 因子2,
        "Alpha3": 因子3,
        "Alpha4": 因子4,
        "Alpha6": 因子6,
        "Alpha8": 因子8,
        "Alpha9": 因子9,
        "Alpha10": 因子10,
        "Alpha12": 因子12,
        "Alpha13": 因子13,
        "Alpha14": 因子14,
        "Alpha15": 因子15,
        "Alpha16": 因子16,
    }


def 计算第二批因子(
    开盘价: pd.DataFrame,
    收盘价: pd.DataFrame,
    最高价: pd.DataFrame,
    最低价: pd.DataFrame,
    成交量: pd.DataFrame,
    横截面掩码: pd.DataFrame,
) -> dict[str, pd.DataFrame]:
    """计算剩余6个仅依赖OHLCV的Alpha101因子。"""
    日收益 = 日收益率(收盘价)

    因子18 = -_掩码横截面排名(
        时间序列标准差((收盘价 - 开盘价).abs(), 5)
        + (收盘价 - 开盘价)
        + 相关系数(收盘价, 开盘价, 10),
        横截面掩码,
    )

    因子20 = (
        -_掩码横截面排名(
            开盘价 - 延迟(最高价, 1),
            横截面掩码,
        )
        * _掩码横截面排名(
            开盘价 - 延迟(收盘价, 1),
            横截面掩码,
        )
        * _掩码横截面排名(
            开盘价 - 延迟(最低价, 1),
            横截面掩码,
        )
    )

    因子22 = -(
        差分(相关系数(最高价, 成交量, 5), 5)
        * _掩码横截面排名(
            时间序列标准差(收盘价, 20),
            横截面掩码,
        )
    )

    二十日最高价均值 = 时间序列求和(最高价, 20) / 20
    因子23 = (-差分(最高价, 2)).where(
        二十日最高价均值.lt(最高价),
        0.0,
    )
    因子23 = 因子23.where(二十日最高价均值.notna())

    因子33 = _掩码横截面排名(
        -(1 - 开盘价 / 收盘价.replace(0, np.nan)),
        横截面掩码,
    )

    短长波动率比值排名 = _掩码横截面排名(
        时间序列标准差(日收益, 2)
        / 时间序列标准差(日收益, 5).replace(0, np.nan),
        横截面掩码,
    )
    一日价差排名 = _掩码横截面排名(
        差分(收盘价, 1),
        横截面掩码,
    )
    因子34 = _掩码横截面排名(
        (1 - 短长波动率比值排名) + (1 - 一日价差排名),
        横截面掩码,
    )

    return {
        "Alpha18": 因子18,
        "Alpha20": 因子20,
        "Alpha22": 因子22,
        "Alpha23": 因子23,
        "Alpha33": 因子33,
        "Alpha34": 因子34,
    }


def 宽表因子转长表(
    因子结果: dict[str, pd.DataFrame],
    最终样本掩码: pd.DataFrame,
) -> pd.DataFrame:
    """将同维度的因子宽表转换为股票—日期长表。"""
    if not 因子结果:
        raise ValueError("因子结果不能为空")

    日期索引 = 最终样本掩码.index
    股票代码 = 最终样本掩码.columns
    长表索引 = pd.MultiIndex.from_product(
        [日期索引, 股票代码],
        names=["日期", "证券代码"],
    )
    样本有效 = 最终样本掩码.to_numpy(dtype=bool).ravel()
    长表 = pd.DataFrame(index=长表索引[样本有效])

    for 因子名称, 原始因子宽表 in 因子结果.items():
        因子宽表 = 原始因子宽表.reindex(
            index=日期索引,
            columns=股票代码,
        )
        长表[因子名称] = 因子宽表.to_numpy().ravel()[样本有效]

    return 长表.reset_index()
